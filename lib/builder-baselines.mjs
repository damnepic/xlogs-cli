// BUILDER BASELINES (INV-31, 2026-10-06). One untouched starter app per AI builder, deployed under our
// own accounts and scanned with the same engine. A finding on a user's app can then say something no
// other scanner can: whether that builder's own starter ships the same gap, on a dated scan.
//
// MEASURED, NEVER ASSUMED. A note appears only when the starter's check for that finding's category
// actually COMPLETED: "found" (the starter has it too) or "clear" (the starter does not). A check that
// could not run on the starter, or a builder with no baseline, produces no note at all. No imports,
// so the engine, the CLI and the browser can all read it.
//
// The data below is written by scripts/builder-baseline.mjs, which refuses to record an app the
// scanner does not fingerprint as that builder. Each entry carries the date and the engine commit, so
// a reader can see how old the comparison is.

// BEGIN BASELINES (generated by scripts/builder-baseline.mjs; do not edit by hand)
export const BASELINES = [];
// END BASELINES

// The list baselineNote reads by default. Tests swap it; production never does.
let ACTIVE = BASELINES;
export function __setBaselinesForTest(list) { ACTIVE = list || BASELINES; }

/**
 * The baseline record for one scan of a starter app. `categoryCheck` maps finding category to the
 * receipt check that covers it (lib/diff.mjs CATEGORY_CHECK), passed in so this module stays pure.
 */
export function baselineFromResult(result, categoryCheck, { builderId, label, url, at, commit = null }) {
  const found = new Set((result.findings || []).map((f) => f.category));
  const status = new Map((result.receipt || []).map((r) => [r.id, r.status]));
  const checked = {};
  for (const [category, checkId] of Object.entries(categoryCheck)) {
    if (found.has(category)) checked[category] = "found";
    else checked[category] = status.get(checkId) === "clear" ? "clear" : status.get(checkId) === "found" ? "clear-for-this-category" : (status.get(checkId) || "not-run");
  }
  return { builder: builderId, label, url, scannedAt: new Date(at).toISOString(), commit, checked };
}

/**
 * The note for one finding on a user's app, or null. `builderId` comes from the scan's own
 * fingerprint, so a note is never attached to an app the scanner did not attribute to that builder.
 */
export function baselineNote(category, builderId, baselines = ACTIVE) {
  if (!category || !builderId) return null;
  const b = baselines.find((x) => x.builder === builderId);
  if (!b) return null;
  const s = b.checked?.[category];
  const date = String(b.scannedAt || "").slice(0, 10);
  if (s === "found") {
    return { kind: "same", builder: b.label, scannedAt: date, text: `The untouched ${b.label} starter app we scanned on ${date} has the same finding, so it is part of what ${b.label} ships by default.` };
  }
  if (s === "clear" || s === "clear-for-this-category") {
    return { kind: "not-in-starter", builder: b.label, scannedAt: date, text: `The untouched ${b.label} starter app we scanned on ${date} does not have this, so it is not a ${b.label} default.` };
  }
  return null;
}
